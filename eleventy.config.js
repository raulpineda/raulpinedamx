export default function (eleventyConfig) {
  // Passthrough copy
  eleventyConfig.addPassthroughCopy({ public: "." });
  eleventyConfig.addPassthroughCopy("src/js");

  // Icon shortcode
  eleventyConfig.addShortcode("icon", function (name, size = 32) {
    const path = icons[name];
    if (!path) return "";
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">${path}</svg>`;
  });

  // Posts collection
  eleventyConfig.addCollection("posts", function (collectionApi) {
    return collectionApi.getFilteredByGlob("src/posts/*.md");
  });

  // Process CSS through PostCSS/Tailwind
  eleventyConfig.addTemplateFormats("css");
  eleventyConfig.addExtension("css", {
    outputFileExtension: "css",
    compile: async function (inputContent, inputPath) {
      if (!inputPath.includes("styles/styles.css")) return;
      const result = await postcss([tailwindcss, autoprefixer]).process(
        inputContent,
        { from: inputPath },
      );
      return async () => result.css;
    },
  });

  // Watch for template changes to rebuild CSS
  eleventyConfig.addWatchTarget("src/**/*.njk");
  eleventyConfig.addWatchTarget("src/**/*.md");

  return {
    dir: {
      input: "src",
      output: "_site",
      includes: "_includes",
      data: "_data",
    },
  };
}
